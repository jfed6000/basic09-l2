#!/usr/bin/env python3
"""Generate os9/basic09-l2/kwtab.asm, the editor's keyword table for syntax
colours, from the compiler's own keyword table (KEYTAB in src/comand.asm).

Statements, reserved words and operator words (STMBEG, RESRVD, OPRTR) are
keywords; the rest (FNCREF) are functions.  The editor's own words
(EXTRA: DEFTYPE, USE) are keywords too.

Table format (kw_find in hl.asm):
    kwidx   offsets (fdb, from kwtab), one per first letter from A to
            KWLAST, the last letter that starts a word
    kwtab   per letter: the keywords, a 0 byte, then the functions and
            another 0 byte; each word is the rest of its name (fcs).
            A name of one letter has no entry.

usage: mkkw.py [<comand.asm> [<out.asm>]]
"""
import os
import re
import sys

top = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(top, 'src', 'comand.asm')
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(top, 'os9', 'basic09-l2', 'kwtab.asm')

lines = open(src, encoding='latin1').read().splitlines()
start = next(i for i, l in enumerate(lines) if l.startswith('KEYTAB'))
words = {}
kind = None
for l in lines[start + 1:]:
    if re.match(r'^\s+fdb\s+0\b', l):
        break
    m = re.match(r'^\s+fcb\s+T\.\w+,(\w+)', l)
    if m:
        kind = m.group(1)
        continue
    m = re.match(r'^\S*\s+fcs\s+"([^"]+)"', l)
    if m and kind:
        cls = 'KC.FN' if kind == 'FNCREF' else 'KC.KW'
        words[m.group(1).upper()] = cls
        kind = None

EXTRA = ('DEFTYPE', 'USE')         # the editor's own: DEFTYPE blocks
for w in EXTRA:
    words[w] = 'KC.KW'
letters = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'
last = max(w[0] for w in words if len(w) > 1)
letters = letters[:letters.index(last) + 1]
o = ['* kwtab.asm - generated by tools/mkkw.py from KEYTAB in src/comand.asm;',
     '* do not edit.  %d words.' % len(words), '',
     "KWLAST              equ       '%s" % last, '',
     'kwidx']
for c in letters:
    o.append('                    fdb       kw_%s-kwtab' % c)
o.append('kwtab')
for c in letters:
    o.append('kw_%s' % c)
    for cls in ('KC.KW', 'KC.FN'):
        for w in sorted(x for x in words if x[0] == c and len(x) > 1 and words[x] == cls):
            o.append('                    fcs       "%s"' % w[1:])
        o.append('                    fcb       0')
open(out, 'w').write('\n'.join(o) + '\n')
print('%s: %d words' % (out, len(words)))
